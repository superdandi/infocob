export default function CircuitDrawAnimation() {
  const svgRef = useRef<SVGSVGElement>(null);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    if (!svgRef.current) return;
    const paths_ = svgRef.current.querySelectorAll("path.circuit-draw");
    paths_.forEach((p) => {
      const len = (p as SVGPathElement).getTotalLength();
      (p as SVGPathElement).style.setProperty("--len", String(len));
      p.setAttribute("stroke-dasharray", String(len));
      p.setAttribute("stroke-dashoffset", String(len));
    });
    setReady(true);
  }, []);

  return (
    <div className="absolute inset-0 pointer-events-none overflow-hidden">
      <svg
        ref={svgRef}
        viewBox="220.8013 333.9288 168.4381 123.3387"
        className="w-full h-full transition-opacity duration-700"
        style={{ opacity: ready ? 1 : 0 }}
        preserveAspectRatio="xMidYMid slice"
      >
        <g transform="translate(0, 791.1963) scale(1, -1)">
          <g
            fill="none"
            stroke="currentColor"
            strokeWidth="1.5"
            strokeLinecap="round"
            strokeLinejoin="round"
            className="opacity-[0.06] dark:opacity-[0.08]"
          >
            {paths.map((d, i) => (
              <path
                key={i}
                className="circuit-draw animate-circuit-draw"
                d={d}
                style={{
                  animationDelay: `${i * 0.6}s`,
                  animationDuration: "2.5s",
                }}
              />
            ))}
          </g>
        </g>
      </svg>
    </div>
  );
}
